#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""WFA-DEMO - the whole robustness pipeline on data that is openly fake.

WHY THIS EXISTS
---------------
A tool that judges trading systems is useless if nobody can see what its output
looks like before trusting it with a real study. Waiting for a 10-window MT5
sweep to finish before finding out that the report is unreadable - or that the
gates are wired to the wrong column - is a bad way to learn.

This builds a complete, DETERMINISTIC synthetic study in one command:

  * a 420-trade out-of-sample list with a 58% win rate and a +1.05/-1.00 payoff
    (a real-looking edge that is only just there, not a fantasy);
  * a 3-parameter optimisation grid shaped as a broad bowl with ONE deliberate
    isolated spike, so the plateau chooser has something to refuse;
  * six walk-forward windows whose OOS segments decay - the fitter the IS
    result looks, the less of it survives, which is the failure this whole
    discipline exists to catch;
  * 60 random-entry benchmarks with the same trade count and exit profile;
  * a manifest wiring all of it into tools/wfa_stats.py, and the rendered
    report.

WHAT IT PROVES, AND WHAT IT DOES NOT
------------------------------------
It proves the pipeline runs end to end and that the report is legible. Every
number in the output is generated by this file: **none of it describes XAUUSD,
EURUSD, QSMC, or any real market.** The verdict it prints is a demonstration of
the gate machinery, not a finding. Reading it as a backtest result would be the
exact category error this repository spends its comments preventing.

The expected verdict is NO-GO with two failures - walk-forward efficiency and
the deflated Sharpe - because a decaying synthetic edge is exactly what those
two gates are for. If you ever see a clean GO from this demo, the gates moved.

Usage:
  python3 tools/wfa_demo.py --out out/wfa/demo
  python3 tools/wfa_demo.py --out /tmp/demo --iterations 300 --benchmarks 40 --quiet
"""
from __future__ import annotations

import argparse
import datetime as dt
import io
import json
import os
import random
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import wfa_stats as S

BANNER = ("SYNTHETIC STUDY - generated by tools/wfa_demo.py. Every number below "
          "comes from a random-number generator inside this file and describes "
          "no market, no broker and no QSMC build.")


def _write(path, text):
    parent = os.path.dirname(os.path.abspath(path))
    if parent and not os.path.isdir(parent):
        os.makedirs(parent, exist_ok=True)
    with io.open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


# ---------------------------------------------------------------------------
# Fixtures
# ---------------------------------------------------------------------------

def make_trades(seed: int, count: int = 420):
    """A positive-but-thin edge: 58% wins at +1.05 / -1.00, in account currency."""
    rng = random.Random(seed)
    return [105.0 if rng.random() < 0.58 else -100.0 for _ in range(count)]


def trades_csv(profits) -> str:
    t = dt.datetime(2020, 7, 1, 8, 0)
    lines = ["time,profit"]
    for p in profits:
        lines.append("%s,%.2f" % (t.strftime("%Y-%m-%d %H:%M:%S"), p))
        t += dt.timedelta(hours=6)
    return "\n".join(lines) + "\n"


def make_grid():
    """3-parameter bowl with the maximum in the interior and one corner spike.

    Score is deliberately a smooth quadratic so the plateau is a real plateau,
    and the spike is ~1000x the rest so a chooser that ranks by the cell's own
    result is guaranteed to pick it - which is the mistake under test.
    """
    rows = ["InpRsiPeriod,InpAtrMult,InpHoldBars,Profit,Trades,Profit Factor,Sharpe Ratio"]
    for rsi in range(10, 22, 2):
        for atr in (1.0, 1.5, 2.0, 2.5, 3.0):
            for hold in (1, 2, 3, 4, 5):
                v = (2000.0 - 120.0 * ((rsi - 16.0) / 6.0) ** 2
                     - 900.0 * ((atr - 2.0) / 1.0) ** 2
                     - 150.0 * ((hold - 3.0) / 2.0) ** 2)
                v = max(v, 50.0)
                if (rsi, atr, hold) == (10, 1.0, 1):
                    v = 900000.0
                trades = 240
                rows.append("%d,%g,%d,%.2f,%d,%.3f,%.4f"
                            % (rsi, atr, hold, v, trades,
                               1.15 + v / 12000.0, v / 9000.0))
    return "\n".join(rows) + "\n"


def make_benchmarks(seed: int, count: int = 60, trades: int = 420):
    """Random entries, SAME exit profile (mean 0, sd ~120) and trade count."""
    rng = random.Random(seed + 991)
    out = {}
    for i in range(count):
        out["bench/r%03d.csv" % (i + 1)] = trades_csv(
            [round(rng.gauss(0.0, 120.0), 2) for _ in range(trades)])
    return out


def make_windows():
    """Six windows whose OOS keeps less of the IS result every time."""
    windows = []
    for i in range(6):
        oos = (420.0 - 30.0 * i) if i != 4 else -120.0
        windows.append({
            "name": "w%02d" % (i + 1),
            "is_start": "%d-01-01" % (2018 + i // 2),
            "is_end": "%d-01-01" % (2020 + i // 2),
            "oos_start": "%d-01-01" % (2020 + i // 2),
            "oos_end": "%d-07-01" % (2020 + i // 2),
            "is_net_profit": 900.0 + 40.0 * i,
            "oos_net_profit": oos,
            "params": {"InpRsiPeriod": 16, "InpAtrMult": 2.0, "InpHoldBars": 3},
        })
    return windows


def build_demo(out_dir: str, seed: int = 20261108, iterations: int = 2000,
               benchmarks: int = 60) -> str:
    """Write the fixtures and the manifest. Returns the manifest path."""
    if os.path.isdir(out_dir):
        shutil.rmtree(out_dir)
    os.makedirs(out_dir, exist_ok=True)

    profits = make_trades(seed)
    _write(os.path.join(out_dir, "oos_trades.csv"), trades_csv(profits))
    _write(os.path.join(out_dir, "w01_opt.tidy.csv"), make_grid())
    for rel, text in make_benchmarks(seed, benchmarks).items():
        _write(os.path.join(out_dir, rel), text)

    manifest = {
        "_note": BANNER,
        "label": "synthetic demo (NOT a QSMC result): 3-parameter XAUUSD-shaped study",
        "trades": "oos_trades.csv",
        "start_equity": 10000.0,
        "compounding": False,
        "selection": {"InpRsiPeriod": 16, "InpAtrMult": 2.0, "InpHoldBars": 3},
        "plateau": {
            "runs": "w01_opt.tidy.csv",
            "params": ["InpRsiPeriod", "InpAtrMult", "InpHoldBars"],
            "score": "net_profit",
            "min_trades": 100,
            "k": 4,
            "heatmap": ["InpRsiPeriod", "InpAtrMult"],
            "agg": "mean",
        },
        "windows": make_windows(),
        "trials": 150,
        "mc": {"iterations": iterations, "seed": seed % 100000, "bootstrap": False},
        "benchmarks": ["bench/r%03d.csv" % (i + 1) for i in range(benchmarks)],
        "benchmark_metric": "net_profit",
        "cost_stress": {"extra_cost_per_trade": 12.0},
        "gates": {},
    }
    path = os.path.join(out_dir, "study.json")
    _write(path, json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    return path


# ---------------------------------------------------------------------------
# Run
# ---------------------------------------------------------------------------

VERDICT_ORDER = ("gate", "value", "threshold", "status")


def run_demo(out_dir: str, seed: int = 20261108, iterations: int = 2000,
             benchmarks: int = 60, quiet: bool = False) -> dict:
    manifest_path = build_demo(out_dir, seed, iterations, benchmarks)
    with io.open(manifest_path, encoding="utf-8") as fh:
        manifest = json.load(fh)
    report = S.run_study(manifest, out_dir, generated="synthetic demo (fixed inputs)")
    report["label"] = BANNER + " — " + report["label"]
    text = S.render_report(report, report["gates"])
    _write(os.path.join(out_dir, "report.md"), text)
    if not quiet:
        print(BANNER)
        print("")
        print("%-34s %-22s %s" % ("gate", "measured", "verdict"))
        for g in report["gates"]:
            print("%-34s %-22s %s" % (g["gate"], str(g["value"])[:22], g["status"]))
        print("")
        print("report: %s" % os.path.join(out_dir, "report.md"))
        fails = [g for g in report["gates"] if g["status"] == "FAIL"]
        print("verdict: %s (%d gate(s) failed)"
              % ("NO-GO" if fails else "GO", len(fails)))
        print("A NO-GO here is the EXPECTED result: the synthetic edge decays "
              "across windows,\nwhich is exactly what WFE and the deflated "
              "Sharpe are built to catch.")
    return report


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Build and judge a deterministic SYNTHETIC walk-forward study.")
    ap.add_argument("--out", default=os.path.join("out", "wfa", "demo"))
    ap.add_argument("--seed", type=int, default=20261108)
    ap.add_argument("--iterations", type=int, default=2000)
    ap.add_argument("--benchmarks", type=int, default=60)
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)
    try:
        run_demo(args.out, args.seed, args.iterations, args.benchmarks, args.quiet)
    except (ValueError, KeyError, OSError) as exc:
        print("ERROR: %s" % exc, file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
