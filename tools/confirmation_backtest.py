#!/usr/bin/env python3
"""Generate the deterministic 3-month confirmation-engine surrogate report.

This is a replay of the compiled CE score/state/time/risk layers over a fixed
synthetic M1 price path. It is NOT MetaEditor F7, NOT MetaTrader Strategy
Tester, NOT broker tick data and NOT evidence of a live-trading edge.

Usage:
  python3 tools/confirmation_backtest.py            # write the report
  python3 tools/confirmation_backtest.py --check    # verify the committed report
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))

import confirmation_native as cn  # noqa: E402

REPORT = ROOT / "docs" / "CONFIRMATION_ENGINE_TEST_BACKTEST_2026-11-25.md"


def cell(value) -> str:
    return str(value).replace("|", "\\|").replace("\n", "<br>")


def table(headers, rows) -> str:
    out = ["| " + " | ".join(cell(h) for h in headers) + " |",
           "|" + "|".join(["---"] * len(headers)) + "|"]
    for row in rows:
        out.append("| " + " | ".join(cell(v) for v in row) + " |")
    return "\n".join(out)


def num(value, digits=2) -> str:
    try:
        return ("%.*f" % (digits, float(value))).rstrip("0").rstrip(".")
    except (TypeError, ValueError):
        return str(value)


def reject_text(metrics: dict) -> str:
    items = metrics.get("rejects", {})
    return "; ".join("%s=%s" % (k, v) for k, v in sorted(items.items())) or "none"


def metric_row(label: str, m: dict):
    return [label, m["evaluations"], m["enter_dry_run"], m["near_miss"],
            m["shadow_fills"], m["wins"], m["losses"], num(m["sum_r"]),
            num(m["max_drawdown_r"]), num(m["avg_score"]),
            num(m["avg_risk_scale"]), num(m["avg_lots"]), reject_text(m)]


def render_report(data: dict) -> str:
    canonical = json.dumps(data, sort_keys=True, separators=(",", ":"))
    digest = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    wf = data["walk_forward"]
    baseline_rows = [metric_row("baseline", data["baseline"])]
    wf_rows = [metric_row("in-sample 2026-08-25..2026-10-24", wf["in_sample"]),
               metric_row("holdout 2026-10-25..2026-11-24", wf["holdout"])]
    sensitivity_rows = []
    for row in data["sensitivity"]:
        p, m = row["params"], row["metrics"]
        sensitivity_rows.append([
            row["label"], "%s/%s" % (p["tier_a"], p["tier_b"]), p["min_htf"],
            num(p["max_spread_points"]), p["entry_mode"], m["shadow_fills"],
            num(m["sum_r"]), num(m["max_drawdown_r"]), num(m["avg_score"]),
            reject_text(m)])
    warnings = "\n".join("- " + w for w in data["warnings"])

    return f"""# Confirmation Engine — 3-Month Deterministic Surrogate Backtest

**Generated by:** `tools/confirmation_backtest.py` from `tools/confirmation_native.py` and `tools/qats_sim/qsmc_ce_replay.inc`.<br>
**Engine:** `MQL5/Experts/QSMC_ConfirmationEngine.mq5`<br>
**Verdict:** **{data["status"]}** — {data["days"]} days, {data["m1_bars_in_window"]} in-window M1 bars, {data["setups"]} setups, {data["orders_sent"]} orders sent.<br>
**Canonical result SHA-256:** `{digest}`.

> This is an offline synthetic surrogate, **not** MetaTrader Strategy Tester, **not** MetaEditor F7, **not** broker tick data, **not** broker-latency measurement and **not** a live/demo MT5 result. The synthetic R figures are a deterministic shadow simulation. They are **not evidence of profitability or an edge**. The engine is disarmed: `InpDryRun=true`, `InpAllowLiveOrders=false`, `InpAllowRealTrading=false`.

## 1. Method

| Item | Contract |
|---|---|
| Window | {data["start_utc_iso"]} → {data["end_utc_iso"]} ({data["days"]} days), split at {data["split_utc_iso"]} |
| Bars | {data["m1_bars_in_window"]} in-window M1 bars plus a deterministic {data["m1_bars_with_synthetic_tail"] - data["m1_bars_in_window"]}-bar tail for forward path resolution |
| Setups | {data["setups"]} = two per day at 08:30Z (London) and 15:30Z (New York), fixed LCG seed `20261125` |
| Price path | deterministic bounded random walk with a fixed sinusoidal drift; no broker ticks, no real calendar, no variable-spread feed, no slippage model |
| Time layer | `CE_SessionOfUtc`, `CE_UtcToBrokerServer`, `CE_ServerToUtc`, EU/US DST rules from the real engine; {data["server_roundtrip_checks"]} server round-trip checks, {data["server_roundtrip_mismatches"]} mismatches |
| Decision layers | `CE_ScoreComponents`, `CE_ApplyDecision`, `CE_BuildPlan`, `CE_CalcLots`, `CE_BreakEvenSl` from the compiled MQL5 source |
| AI | disabled in the surrogate; the optional opinion is separately replayed in `docs/CONFIRMATION_ENGINE_REPLAY_2026-11-25.md` |
| Executor | no `CE_PlaceOrder`; dry-run account state; `orders_sent={data["orders_sent"]}` |
| Shadow outcome | if an `ENTER_DRY_RUN` plan is ready, a synthetic fill is looked for within 60 M1 bars, then final TP/SL within 240 M1 bars; partial TP, commissions, swap, latency and real fills are not modelled |

Every setup resets the account counters: no compounding, no daily-loss latch is expected to accumulate, and no position is actually opened. The R figures therefore describe the synthetic path plus the engine's plan geometry, not account performance.

## 2. Baseline

{table(["Series", "Evals", "ENTER_DRY_RUN", "NEAR_MISS", "Shadow fills", "Wins", "Losses", "Sum R", "Max DD R", "Avg score", "Avg risk scale", "Avg lots", "Rejects"], baseline_rows)}

## 3. Walk-forward split

{table(["Series", "Evals", "ENTER_DRY_RUN", "NEAR_MISS", "Shadow fills", "Wins", "Losses", "Sum R", "Max DD R", "Avg score", "Avg risk scale", "Avg lots", "Rejects"], wf_rows)}

The split is chronological: {data["in_sample_days"]} in-sample days and {data["holdout_days"]} holdout days. Parameters are **not** optimised on the in-sample half; the same baseline thresholds are applied to both halves. This is a stability/display check, not a walk-forward optimisation claim.

## 4. Parameter sensitivity

{table(["Set", "A/B", "Min HTF", "Max spread", "Mode", "Shadow fills", "Sum R", "Max DD R", "Avg score", "Rejects"], sensitivity_rows)}

Interpretation:

- `strict-A` reduces the number of accepted synthetic setups through the documented score floor.
- `tight-spread` shows that execution quality is a real gate, not a display-only score: spreading the surrogate above 20 points rejects most rows with `SPREAD_INVALID`.
- Momentum and reversal modes share the same synthetic pullback/second-reaction price in this surrogate, so their aggregate R figures can coincide. That is a property of the fixture, not evidence that the modes are equivalent on broker data.
- HTF counter-alignment changes score and risk scale; it is not a rigid directional veto.

## 5. Warnings

{warnings}

## 6. Operator-only validation still required

1. Press F7 in MetaEditor for `MQL5/Experts/QSMC_ConfirmationEngine.mq5`.
2. Run a real XAUUSD M1 every-tick variable-spread Strategy Tester study for at least three months using broker ticks and the operator's exact symbol/account settings.
3. Run a 24-hour MT5 DEMO observation with the executor disarmed; compare Experts logs and the terminal CSV to `docs/CONFIRMATION_ENGINE_REPLAY_2026-11-25.md`.
4. Re-run `tools/confirmation_replay.py --check`, `tools/test_confirmation_replay.py`, `tools/confirmation_backtest.py --check` and `tools/test_confirmation_backtest.py` after any source or threshold change.
5. Only an explicit separate authorisation decision can consider arming live orders. No preset in this repository arms REAL or live trading for the confirmation engine.

**No live trading is enabled by this report or by the default inputs.**
"""


def generate():
    data, rc = cn.run_json_mode("backtest")
    if data.get("status") == "SKIP":
        return None, rc
    return {"report": render_report(data), "data": data}, 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="compare committed report byte-for-byte")
    args = ap.parse_args(argv)

    artifacts, rc = generate()
    if artifacts is None:
        print("SKIP confirmation backtest: no usable C++17 host compiler")
        return rc
    text = artifacts["report"]
    if args.check:
        if not REPORT.is_file() or REPORT.read_text(encoding="utf-8") != text:
            print("FAIL stale confirmation backtest report: docs/CONFIRMATION_ENGINE_TEST_BACKTEST_2026-11-25.md")
            print("Run python3 tools/confirmation_backtest.py")
            return 1
        print("PASS confirmation backtest report is deterministic and current")
        return 0
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(text, encoding="utf-8", newline="")
    print("WROTE %s" % REPORT.relative_to(ROOT))
    print("This surrogate is NOT Strategy Tester, NOT broker ticks and NOT evidence of a trading edge.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
