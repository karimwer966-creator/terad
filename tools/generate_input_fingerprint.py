"""Generate a complete host input fingerprint; --check fails on manifest drift.
Explicit double serialization, no raw input values are logged or persisted.
"""
from pathlib import Path
import re,sys
root=Path(__file__).resolve().parents[1]
paths=['nadir2.mq5','MQL5/Include/QSMC/QSMC_Preset.mqh',
       'MQL5/Include/QSMC/QSMC_LiquidityValue.mqh',
       'MQL5/Include/QSMC/QSMC_UnifiedDecision.mqh',
       'MQL5/Include/QSMC/QSMC_IncidentSafety.mqh']
def _strip_comments(source):
    # Preserve quoted literals (including color C'r,g,b') and line boundaries.
    token=re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'')
    return token.sub(lambda m: re.sub(r'[^\n]', ' ', m[0])
                     if m[0].startswith(('//','/*')) else m[0],source)

def _delimiters(text,delimiter):
    stack=[]; quote=None; escaped=False
    pairs={')':'(',']':'[','}':'{'}
    for i,ch in enumerate(text):
        if quote:
            if escaped: escaped=False
            elif ch=='\\': escaped=True
            elif ch==quote: quote=None
        elif ch in ('"',"'"): quote=ch
        elif ch in '([{': stack.append(ch)
        elif ch in ')]}':
            if not stack or stack.pop()!=pairs[ch]:
                raise ValueError('unbalanced input expression')
        elif ch==delimiter and not stack: yield i
    if quote or stack: raise ValueError('unterminated input expression')

def parse_inputs(source):
    source=_strip_comments(source)
    entries=[]
    for match in re.finditer(r'^\s*input\s+(\w+)\s+',source,re.M):
        kind=match[1]
        if kind=='group': continue
        tail=source[match.end():]
        end=next(_delimiters(tail,';'),None)
        if end is None: raise ValueError('input declaration missing semicolon')
        declaration=tail[:end]
        cuts=[-1]+list(_delimiters(declaration,','))+[len(declaration)]
        for lo,hi in zip(cuts,cuts[1:]):
            item=declaration[lo+1:hi].strip()
            field=re.fullmatch(r'(\w+)\s*=\s*(.+)',item,re.S)
            if not field: raise ValueError('unsupported input declarator: '+item)
            entries.append((kind,field[1],field[2].strip()))
    return entries

def value(t,v):
    if t=='string':return v
    if t=='double':return f'DoubleToString({v},16)'
    return f'IntegerToString((long)({v}))'
def main():
    entries=[]
    for name in paths:
        entries.extend(parse_inputs((root/name).read_text()))
    assert len(entries)==len({n for _,n,_ in entries}), "duplicate input identity"
    lines=['// Generated by tools/generate_input_fingerprint.py; DO NOT edit.',
           '#ifndef QSMC_INPUT_FINGERPRINT_MQH','#define QSMC_INPUT_FINGERPRINT_MQH',
           f'// Inputs represented: {len(entries)}; order and defaults are part of identity.',
           'void QA_InputHashes(uint &actual,uint &defaults)','{',
           '   static bool ready=false; static uint a=2166136261,d=2166136261;',
           '   if(!ready)','   {']
    for t,n,v in entries:
        lines.append(f'      QSMC_AddInputHash(a,"{n}",{value(t,n)});')
        lines.append(f'      QSMC_AddInputHash(d,"{n}",{value(t,v.strip())});')
    lines+=['      ready=true;','   }','   actual=a; defaults=d;','}','#endif','']
    result='\n'.join(lines);target=root/'MQL5/Include/QSMC/QSMC_InputFingerprint.mqh'
    if '--check' in sys.argv:
        assert target.exists() and target.read_text()==result,'input manifest stale: run tools/generate_input_fingerprint.py'
        print('PASS input fingerprint manifest:',len(entries),'inputs')
    else:target.write_text(result)

if __name__=="__main__":
    main()
