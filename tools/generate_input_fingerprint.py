"""Generate a complete host input fingerprint; --check fails on manifest drift.
Explicit double serialization, no raw input values are logged or persisted.
"""
from pathlib import Path
import re,sys
root=Path(__file__).resolve().parents[1]
paths=['nadir2.mq5','MQL5/Include/QSMC/QSMC_Preset.mqh',
       'MQL5/Include/QSMC/QSMC_LiquidityValue.mqh',
       'MQL5/Include/QSMC/QSMC_UnifiedDecision.mqh',
       'MQL5/Include/QSMC/QSMC_IncidentSafety.mqh']
entries=[]
for name in paths:
    entries+=re.findall(r'^input\s+(\w+)\s+(Inp\w+)\s*=\s*([^;]+);',(root/name).read_text(),re.M)
assert len(entries)==len({n for _,n,_ in entries}), 'duplicate input identity'
def value(t,v):
    if t=='string':return v
    if t=='double':return f'DoubleToString({v},16)'
    return f'IntegerToString((long)({v}))'
lines=['// Generated by tools/generate_input_fingerprint.py; DO NOT edit.',
       '#ifndef QSMC_INPUT_FINGERPRINT_MQH','#define QSMC_INPUT_FINGERPRINT_MQH',
       f'// Inputs represented: {len(entries)}; order and defaults are part of identity.',
       'void QA_InputHashes(uint &actual,uint &defaults)','{',
       '   static bool ready=false; static uint a=2166136261,d=2166136261;',
       '   if(!ready)','   {']
for t,n,v in entries:
    lines.append(f'      QSMC_AddInputHash(a,"{n}",{value(t,n)});')
    lines.append(f'      QSMC_AddInputHash(d,"{n}",{value(t,v.strip())});')
lines+=['      ready=true;','   }','   actual=a; defaults=d;','}','#endif','']
result='\n'.join(lines);target=root/'MQL5/Include/QSMC/QSMC_InputFingerprint.mqh'
if '--check' in sys.argv:
    assert target.exists() and target.read_text()==result,'input manifest stale: run tools/generate_input_fingerprint.py'
    print('PASS input fingerprint manifest:',len(entries),'inputs')
else:target.write_text(result)
