#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""INPUTS REFERENCE - every input is in the document, and nothing in it is invented.

WHY THIS FILE EXISTS
--------------------
`nadir2.mq5` declares 545 inputs and, before v6.6.25, 303 of them appeared in no
document in this repository. `docs/QSMC_AUTOTRADER.md` is described in
`docs/INDEX.md` as *"the companion EA: every input, every guard, what it refuses"*
and was missing 37 of that file's 71 - including all five of the inputs that
decide how large a position is.

`docs/INPUTS_REFERENCE.md` closes that, but a hand-maintained input list is stale
the day it is written. So the document is generated by
`tools/gen_inputs_reference.py` and this suite keeps it honest. It re-parses the
source **independently** of the generator: if the generator has a bug that drops
an input, this suite still notices, because it counts declarations itself.

WHAT IT CHECKS
--------------
  R1  the checked-in document is byte-identical to what the generator produces.
  R2  every `input` declaration in every shipped program and every
      input-declaring header appears in the document. Counted here, not
      delegated.
  R3  no meaning was invented: every meaning cell that is not
      `UNDOCUMENTED IN SOURCE` appears verbatim in that file's own comments.
  R4  every default in the document equals the source default.
  R5  the `UNDOCUMENTED IN SOURCE` count printed in the document equals an
      independent count of declarations with no comment at all.
  R6  the mirror `MQL5/Indicators/nadir2.mq5` is excluded from the document but
      still declares an identical input set, so the two copies cannot drift.
  R7  the document says it is generated and must not be edited.

Source contract only: not a MetaEditor compile, not a backtest.
"""

import io
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "docs", "INPUTS_REFERENCE.md")
UNDOC = "UNDOCUMENTED IN SOURCE"

CHECKS = [0]
FAILURES = []


def check(cond, label):
    CHECKS[0] += 1
    if cond:
        print("PASS  " + label)
    else:
        print("FAIL  " + label)
        FAILURES.append(label)


def read(path):
    return io.open(path, encoding="utf-8", errors="replace").read().replace("\r\n", "\n")


DECL = re.compile(r"^input\s+([A-Za-z_][\w:]*(?:\s*<[^>]*>)?)\s+(.+?);\s*(?://\s*(.*))?$")
NAMES = re.compile(r"([A-Za-z_]\w*)\s*=\s*([^,]+?)(?=,\s*[A-Za-z_]\w*\s*=|$)")


def tracked_mql():
    out = subprocess.check_output(["git", "ls-files", "*.mq5", "*.mqh"], cwd=ROOT, text=True)
    return [f for f in out.split() if os.path.isfile(os.path.join(ROOT, f))]


def declarations(rel):
    """[(line, type, name, default, trailing comment or None)] for one file.

    One `input` line may declare several names (`input int A = 1, B = 2;`), and
    this parser is deliberately independent of the generator's, so it expands
    them itself rather than trusting the document.
    """
    lines = read(os.path.join(ROOT, rel)).split("\n")
    out = []
    for i, l in enumerate(lines):
        if not l.startswith("input ") or l.startswith("input group"):
            continue
        m = DECL.match(l)
        if not m:
            continue
        for name, default in NAMES.findall(m.group(2)):
            out.append((i + 1, m.group(1).strip(), name, default.strip(),
                        (m.group(3) or "").strip() or None))
    return out


def comment_text(rel):
    """Every comment line in a file, joined, for the verbatim-meaning test."""
    out = []
    for l in read(os.path.join(ROOT, rel)).split("\n"):
        s = l.strip()
        if s.startswith("//"):
            out.append(re.sub(r"^//+\s?", "", s))
        elif "//" in l:
            out.append(l.split("//", 1)[1].strip())
    return "\n".join(out)


# ---------------------------------------------------------- R1 freshness
rc = subprocess.call([sys.executable, os.path.join(ROOT, "tools", "gen_inputs_reference.py"),
                      "--check"], cwd=ROOT, stdout=subprocess.DEVNULL)
check(rc == 0, "R1 docs/INPUTS_REFERENCE.md is exactly what the generator produces")

doc = read(DOC) if os.path.isfile(DOC) else ""
check(doc != "", "R1 the document exists and is non-empty")

# ------------------------------------------- R2 independent coverage count
MIRROR = "MQL5/Indicators/nadir2.mq5"
files = [f for f in tracked_mql() if f != MIRROR and not f.startswith("tools/")]
src_names = {}
for f in files:
    for _, _, name, _, _ in declarations(f):
        src_names.setdefault(name, set()).add(f)

doc_names = set(re.findall(r"^\| `([A-Za-z_]\w*)` \|", doc, re.M))
missing = sorted(n for n in src_names if n not in doc_names)
check(not missing,
      "R2 every declared input name appears in the document (%d declared, %d missing%s)"
      % (len(src_names), len(missing), ": " + ", ".join(missing[:8]) if missing else ""))

extra = sorted(n for n in doc_names if n not in src_names)
check(not extra,
      "R2 the document lists no input that the source does not declare (%s)"
      % (", ".join(extra[:8]) if extra else "none"))

total_decl = sum(len(declarations(f)) for f in files)
m = re.search(r"\*\*Total: (\d+) inputs across (\d+) files", doc)
check(m is not None and int(m.group(1)) == total_decl,
      "R2 the document's total (%s) equals an independent count of declarations (%d)"
      % (m.group(1) if m else "?", total_decl))

# ------------------------------------------------- R3 nothing invented
rows = re.findall(r"^\| `([A-Za-z_]\w*)` \| `([^`]*)` \| `([^`]*)` \| \| (.*) \|$", doc, re.M)
check(len(rows) > 0, "R3 the document has parseable input rows (%d)" % len(rows))

# map each input name back to the file(s) that declare it, for the verbatim test
cache = {}
decl_cache = {}
SIBLING = re.compile(r"^declared alongside `([A-Za-z_]\w*)` on one input line$")
invented = []
for name, typ, default, meaning in rows:
    meaning = meaning.replace("\\|", "|").strip()
    if meaning == UNDOC:
        continue
    sib = SIBLING.match(meaning)
    if sib:
        # not a comment - a statement about the declaration form. Verify it the
        # same way: the named sibling must really share the input line.
        partner = sib.group(1)
        ok = False
        for f in sorted(src_names.get(name, ())):
            if f not in decl_cache:
                decl_cache[f] = {}
                for ln, _, n, _, _ in declarations(f):
                    decl_cache[f].setdefault(n, set()).add(ln)
            if decl_cache[f].get(name, set()) & decl_cache[f].get(partner, set()):
                ok = True
                break
        if not ok:
            invented.append("%s: claims to share a line with %s and does not" % (name, partner))
        continue
    for f in sorted(src_names.get(name, ())):
        if f not in cache:
            cache[f] = comment_text(f)
        if meaning in cache[f]:
            break
    else:
        invented.append("%s: %r" % (name, meaning[:60]))
check(not invented,
      "R3 every meaning cell appears verbatim in that file's own comments (%s)"
      % ("; ".join(invented[:5]) if invented else "all %d verified" % len(rows)))

# ------------------------------------------------------- R4 defaults
# Input names are NOT unique across programs (InpMagic, InpVerbose and
# InpRiskPercent all appear in more than one file with different defaults), so
# the document is split into its per-file sections and compared inside each.
sections = {}
cur = None
for line in doc.split("\n"):
    h = re.match(r"^## (\S+\.mq[5h])\s*$", line)
    if h:
        cur = h.group(1)
        sections[cur] = {}
        continue
    r = re.match(r"^\| `([A-Za-z_]\w*)` \| `[^`]*` \| `([^`]*)` \| \| ", line)
    if r and cur:
        sections[cur][r.group(1)] = r.group(2).replace("\\|", "|")

check(set(sections) == set(f for f in files if declarations(f)),
      "R4 the document has one section per file that declares inputs (%d sections, %d files)"
      % (len(sections), len([f for f in files if declarations(f)])))

wrong_default = []
for f, decls in ((f, declarations(f)) for f in files):
    sec = sections.get(f, {})
    for _, _, name, default, _ in decls:
        if name not in sec:
            wrong_default.append("%s: %s missing from its section" % (f, name))
        elif sec[name] != default:
            wrong_default.append("%s: %s doc %s, source %s" % (f, name, sec[name], default))
check(not wrong_default,
      "R4 every default in the document equals the source default in its own section (%s)"
      % ("; ".join(wrong_default[:5]) if wrong_default
         else "all %d match" % sum(len(declarations(f)) for f in files)))

# ------------------------------------------------- R5 UNDOCUMENTED count
undoc_src = 0
for f in files:
    lines = read(os.path.join(ROOT, f)).split("\n")
    for i, l in enumerate(lines):
        if not l.startswith("input ") or l.startswith("input group"):
            continue
        m = DECL.match(l)
        if not m:
            continue
        if (m.group(3) or "").strip():
            continue
        if len(NAMES.findall(m.group(2))) > 1:
            continue   # comma-siblings carry no comment of their own by construction
        j = i - 1
        found = False
        while j >= 0 and lines[j].lstrip().startswith("//"):
            if re.sub(r"^\s*//+\s?", "", lines[j]).strip():
                found = True
                break
            j -= 1
        if not found:
            undoc_src += 1
m2 = re.search(r"(\d+) of them undocumented in source", doc)
check(m2 is not None and int(m2.group(1)) == undoc_src,
      "R5 the document's undocumented count (%s) equals an independent count (%d)"
      % (m2.group(1) if m2 else "?", undoc_src))

# ------------------------------------------------------------ R6 mirror
if os.path.isfile(os.path.join(ROOT, MIRROR)):
    mirror_decl = {(n, d) for _, _, n, d, _ in declarations(MIRROR)}
    host_decl = {(n, d) for _, _, n, d, _ in declarations("nadir2.mq5")}
    check(mirror_decl == host_decl,
          "R6 the mirror declares an identical input set (%d inputs)" % len(host_decl))
    check("## %s" % MIRROR not in doc,
          "R6 the mirror is excluded from the document (it would only duplicate nadir2.mq5)")
else:
    check(False, "R6 the shipped mirror exists")

# ------------------------------------------------------------- R7 header
check("generated by `tools/gen_inputs_reference.py`" in doc,
      "R7 the document says which tool generates it")
check("Do not edit it" in doc, "R7 the document says not to edit it by hand")
check("No meaning in\nthis file was invented" in doc or "No meaning in this file was invented" in doc,
      "R7 the document states that no meaning was invented")
check("source-contract ready" in doc,
      "R7 the document carries the source-contract status line")

# ------------------------------------- R8 other documents' coverage claims
# docs/INDEX.md described docs/QSMC_AUTOTRADER.md as *"the companion EA: every
# input, every guard, what it refuses"*. It names 34 of that file's 71 inputs,
# and the 37 it omits include every multiplier that sizes a position. The claim
# was the defect, not the document: an operator guide is allowed to be selective,
# an index is not allowed to say it is exhaustive. So the index now says what the
# document is, and this check holds both numbers.
INDEX = os.path.join(ROOT, "docs", "INDEX.md")
GUIDE = os.path.join(ROOT, "docs", "QSMC_AUTOTRADER.md")
if os.path.isfile(INDEX) and os.path.isfile(GUIDE):
    idx = io.open(INDEX, encoding="utf-8", errors="replace").read()
    guide = io.open(GUIDE, encoding="utf-8", errors="replace").read()
    row = ""
    for line in idx.split("\n"):
        if "QSMC_AUTOTRADER.md" in line and line.startswith("|"):
            row = line
            break
    check(row != "", "R8 docs/INDEX.md has a row for QSMC_AUTOTRADER.md")

    EA_REL = "MQL5/Experts/QSMC_AutoTrader.mq5"
    ea_names = [n for _, _, n, _, _ in declarations(EA_REL)]
    named = sorted(set(n for n in ea_names if n in guide))
    check(len(ea_names) == 71,
          "R8 the EA declares 71 inputs (found %d)" % len(ea_names))
    check(len(named) == 34,
          "R8 QSMC_AUTOTRADER.md names 34 of them (found %d)" % len(named))

    check("every input" not in row,
          "R8 the index no longer claims the operator guide covers every input")
    check("Not an input reference" in row,
          "R8 and says plainly that it is not an input reference")
    check("34" in row and "71" in row,
          "R8 the index states the coverage it actually has (34 of 71)")
    check("INPUTS_REFERENCE.md" in row,
          "R8 and points at the generated reference for the complete list")

    # The sizing inputs are the ones whose absence actually matters, so they are
    # named rather than counted: an operator guide may skip a log switch, it may
    # not silently skip everything that decides how large a position is.
    SIZING = ["InpFixedLotsMaxRiskPercent", "InpMaxAggregateRiskPercent",
              "InpModerateRiskMultiplier", "InpRealMaxAggregateRiskPercent",
              "InpRealMaxRiskPercent", "InpStrongRiskMultiplier",
              "InpWeakRiskMultiplier"]
    absent = [n for n in SIZING if n not in guide]
    check(len(absent) == 7,
          "R8 all seven position-sizing inputs are absent from the operator "
          "guide (%d present) - which is why the index must not call it "
          "exhaustive" % (7 - len(absent)))
    check(all(n in doc for n in SIZING),
          "R8 and every one of them IS in the generated reference")

    # The guide is scoped to the release it was written for. Saying so is the
    # honest fix; retitling it v6.6.25 would claim a currency nobody checked.
    check("v6.6.24" in guide.split("\n")[0],
          "R8 the operator guide still carries the release it was written against")
else:
    check(False, "R8 docs/INDEX.md and docs/QSMC_AUTOTRADER.md both exist")

print("=" * 60)
print("inputs-reference checks: %d checks, failures: %d" % (CHECKS[0], len(FAILURES)))
if FAILURES:
    for f in FAILURES:
        print("  failed: " + f)
    raise SystemExit(1)
print("%d inputs documented from source, %d marked UNDOCUMENTED IN SOURCE."
      % (total_decl, undoc_src))
print("Source contract only: NOT a MetaEditor compile, NOT a backtest.")
