def cell(value) -> str:
    return str(value).replace("|", "\\|").replace("\n", "<br>")


def table(headers, rows) -> str:
    out = ["| " + " | ".join(cell(h) for h in headers) + " |",
           "|" + "|".join(["---"] * len(headers)) + "|"]
    for row in rows:
        out.append("| " + " | ".join(cell(v) for v in row) + " |")
    return "\n".join(out)


def num(value, digits=2) -> str:
    try:
        return ("%.*f" % (digits, float(value))).rstrip("0").rstrip(".")
    except (TypeError, ValueError):
        return str(value)


def server_label(iso: str) -> str:
    # The native helper prints epoch fields with a Z suffix for both calendar
    # views. Broker-server chart time is NOT UTC; label it explicitly.
    return iso[:-1] + " broker-server" if iso.endswith("Z") else iso


def render_csv(data: dict) -> str:
    lines = [data["csv_header"]]
    lines.extend(row["csv"] for row in data["rows"])
    return "\n".join(lines) + "\n"


