def generate():
    data, rc = cn.run_json_mode("replay")
    if data.get("status") == "SKIP":
        return None, rc
    csv_text = render_csv(data)
    report_text = render_report(data, csv_text)
    return {"report": report_text, "csv": csv_text, "data": data}, 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="compare committed artefacts byte-for-byte")
    args = ap.parse_args(argv)

    artifacts, rc = generate()
    if artifacts is None:
        print("SKIP confirmation replay: no usable C++17 host compiler")
        return rc
    wanted = {REPORT: artifacts["report"], CSV: artifacts["csv"]}
    if args.check:
        drift = []
        for path, text in wanted.items():
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                drift.append(str(path.relative_to(ROOT)))
        if drift:
            print("FAIL stale confirmation replay artefacts: " + ", ".join(drift))
            print("Run python3 tools/confirmation_replay.py")
            return 1
        print("PASS confirmation replay artefacts are deterministic and current")
        return 0
    for path, text in wanted.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="")
        print("WROTE %s" % path.relative_to(ROOT))
    print("This replay is NOT MetaEditor F7, NOT Strategy Tester and NOT a live MT5 demo.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
