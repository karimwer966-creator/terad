#!/usr/bin/env python3
"""Build the QSMC v6.6.20 production install ZIP.

The ZIP is a Data-Folder layout, not a compiled release: it contains .mq5/.mqh
sources and presets. MetaEditor F7 is still required on the target terminal.

By default this runs the curated offline gate first. Use --skip-checks only
when out/production/SUMMARY.txt already records a current OFFLINE GO.
"""
from __future__ import print_function

import argparse
import hashlib
import os
import shutil
import subprocess
import sys
import zipfile
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VERSION = "v6.6.22"
OUT_DIR = os.path.join(ROOT, "release")
STAGE = os.path.join(ROOT, "out", "package_stage")


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def run(cmd):
    print("+ " + " ".join(cmd))
    subprocess.check_call(cmd, cwd=ROOT)


def copy_rel(rel, stage):
    src = os.path.join(ROOT, rel)
    if not os.path.isfile(src):
        raise SystemExit("missing required file: " + rel)
    dst = os.path.join(stage, rel)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy2(src, dst)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--skip-checks", action="store_true")
    ap.add_argument("--output", default=os.path.join(OUT_DIR, "QSMC_%s_production.zip" % VERSION))
    args = ap.parse_args()
    os.chdir(ROOT)

    if not args.skip_checks:
        run([sys.executable, "tools/check_production_ready.py", "--timeout", "240"])
    else:
        summary = os.path.join(ROOT, "out", "production", "SUMMARY.txt")
        if not os.path.isfile(summary):
            raise SystemExit("--skip-checks requires out/production/SUMMARY.txt; run check_production_ready.py first")
        text = open(summary, encoding="utf-8").read()
        if "failed=0" not in text:
            raise SystemExit("offline summary is not GO; refusing to package")

    run([sys.executable, "tools/check_release_gate.py"])

    # The deployment copy must be byte-identical to the canonical host.
    a = open(os.path.join(ROOT, "nadir2.mq5"), "rb").read()
    b = open(os.path.join(ROOT, "MQL5", "Indicators", "nadir2.mq5"), "rb").read()
    if a != b:
        raise SystemExit("MQL5/Indicators/nadir2.mq5 is not synchronized with root nadir2.mq5")

    if os.path.isdir(STAGE):
        shutil.rmtree(STAGE)
    os.makedirs(STAGE)
    os.makedirs(OUT_DIR, exist_ok=True)

    files = [
        "MQL5/Indicators/nadir2.mq5",
        "MQL5/Indicators/QSMC_ScannerProbe.mq5",
        "MQL5/Scripts/QSMC_ArbiterTest.mq5",
        "MQL5/Experts/QSMC_AutoTrader.mq5",
        "MQL5/Experts/KLJ_DataFeeder.mq5",
        "INSTALL_AR.md",
        "presets/QSMC_v6.6.20_production_chart.set",
        "presets/QSMC_AutoTrader_v6.6.20_PRODUCTION_SAFE.set",
        "presets/QSMC_AutoTrader_DEMO_0.10_200.set",
        "presets/nadir2_PRODUCTION_XAUUSD.set",
        "MQL5/Scripts/QSMC_ResetGuards.mq5",
        "presets/QSMC_v6.6.20_latency_diagnosis.set",
    ]
    inc = os.path.join(ROOT, "MQL5", "Include", "QSMC")
    files += ["MQL5/Include/QSMC/" + f for f in sorted(os.listdir(inc)) if f.endswith(".mqh")]
    for doc in ("QSMC_BUILD_AND_RUN.md", "QSMC_GO_LIVE_RUNBOOK.md", "QSMC_PRODUCTION_CHECKLIST.md",
                "QSMC_AUTOTRADER.md", "QSMC_WHY_NO_TRADES.md", "QSMC_CHART_READING_AR.md",
                "QSMC_RUNTIME_LOG_REVIEW_AR.md"):
        rel = "docs/" + doc
        if os.path.isfile(os.path.join(ROOT, rel)):
            files.append(rel)
    for rel in files:
        if rel.startswith("presets/") and rel.endswith(".set"):
            # Legacy QSMC bundle only: materialize a preserved test fixture in the output.
            fixture = os.path.join(ROOT, "tools", "fixtures", "legacy_presets", os.path.basename(rel) + ".txt")
            dest = os.path.join(STAGE, rel)
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            shutil.copyfile(fixture, dest)
        else:
            copy_rel(rel, STAGE)

    # Verification evidence generated by the offline gate.
    evidence = {
        "verification/production_ready.log": "out/production-ready.log",
        "verification/production_summary.txt": "out/production/SUMMARY.txt",
        "verification/release_gate.log": "out/release-gate.log",
        "verification/static_check.log": "out/static.log",
    }
    for dst_rel, src_rel in evidence.items():
        src = os.path.join(ROOT, src_rel)
        if os.path.isfile(src):
            dst = os.path.join(STAGE, dst_rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(src, dst)

    try:
        commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT).decode().strip()
        branch = subprocess.check_output(["git", "rev-parse", "--abbrev-ref", "HEAD"], cwd=ROOT).decode().strip()
        dirty = subprocess.call(["git", "diff", "--quiet"], cwd=ROOT) != 0
    except Exception:
        commit, branch, dirty = "unknown", "unknown", True

    manifest = [
        "QSMC production package %s" % VERSION,
        "built_utc=%s" % datetime.now(timezone.utc).isoformat(),
        "branch=%s" % branch,
        "commit=%s%s" % (commit, " (working tree had uncommitted changes)" if dirty else ""),
        "compile_status=NOT COMPILED HERE - MetaEditor F7 required",
        "offline_gate=OFFLINE GO (curated checks); release gate GO (0 warnings)",
        "safety=EA ships ARMED ON DEMO (EXECUTION_DEMO): InpEnableTrading=true, InpDryRun=false; REAL disarmed: InpAllowRealTrading=false, empty login/server confirmations",
        "",
        "files:",
    ]
    sums = []
    for dirpath, _, filenames in os.walk(STAGE):
        for fn in sorted(filenames):
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, STAGE).replace(os.sep, "/")
            if rel in ("MANIFEST.txt", "SHA256SUMS.txt"):
                continue
            digest = sha256(full)
            sums.append("%s  %s" % (digest, rel))
            manifest.append("  %s  %s" % (digest[:16], rel))
    with open(os.path.join(STAGE, "MANIFEST.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(manifest) + "\n")
    with open(os.path.join(STAGE, "SHA256SUMS.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(sorted(sums)) + "\n")

    output = os.path.abspath(args.output)
    if os.path.exists(output):
        os.remove(output)
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for dirpath, _, filenames in os.walk(STAGE):
            for fn in sorted(filenames):
                full = os.path.join(dirpath, fn)
                rel = os.path.relpath(full, STAGE).replace(os.sep, "/")
                z.write(full, rel)
    print("package=%s" % output)
    print("bytes=%d" % os.path.getsize(output))
    print("sha256=%s" % sha256(output))
    print("This package contains sources, not .ex5 binaries. Press F7 in MetaEditor.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
